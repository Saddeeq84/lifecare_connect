5.2. Referral Documentation
All referrals must include:
   • Patient identification and contact information
   • Reason for referral with clinical observations
   • Vital signs and health metrics (if available)
   • Urgency level (routine, urgent, emergency)
   • Any relevant medical history or current medications

5.3. Referral Tracking
   • All referrals are documented in the platform system
   • You can track referral status and outcomes
   • Notifications sent to receiving doctors/facilities
   • Follow-up reminders to ensure patient compliance

