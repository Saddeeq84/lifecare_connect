4.2. Consultation Fee Structure
After free quota exhaustion:
   • Consultation Fee: ₦2,000 per doctor appointment booking
   • Payment deducted from your wallet at time of booking
   • Fees are held in escrow until consultation completion
   • Upon completion, 70% credited to doctor, 30% to platform as service fee

4.3. Appointment Booking Process
You may book doctor appointments for:
   • Your registered patients (tracked by patient ID)
   • Walk-in community members (requires demographic details)
You must provide: patient name/demographics, appointment reason, preferred date/time, and any urgent medical concerns.

4.4. Appointment Obligations
